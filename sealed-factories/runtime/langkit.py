def by_name(name: str) -> Language:
    for language in LANGUAGES:
        if language.name == name:
            return language
    raise KeyError(name)


def probe(language: Language) -> dict:
    if not language.binaries:
        # No toolchain to probe: these packs are static files a browser or interpreter consumes.
        return {"language": language.name, "available": True, "binary": None, "version": None,
                "wanted": []}
    found = next((binary for binary in language.binaries if shutil.which(binary)), None)
    if found is None:
        return {"language": language.name, "available": False, "binary": None, "version": None,
                "wanted": list(language.binaries)}
    version = None
    if language.version_command:
        try:
            done = subprocess.run(language.version_command.replace(language.binaries[0], found,
                                                                   1),
                                  shell=True, capture_output=True, text=True, timeout=25)
            version = (done.stdout or done.stderr).strip().splitlines()[0][:120]
        except (OSError, subprocess.SubprocessError, IndexError):
            version = None
    return {"language": language.name, "available": True, "binary": found, "version": version,
            "wanted": list(language.binaries)}


def detect() -> dict:
    probes = [probe(language) for language in LANGUAGES]
    return {"available": [p["language"] for p in probes if p["available"]],
            "missing": [p["language"] for p in probes if not p["available"]],
            "probes": probes}


def scaffold(language_name: str, name: str) -> dict[str, str]:
    """The files of a runnable project, ready to be written into a workspace."""
    language = by_name(language_name)
    return {path: content.replace("{name}", name) for path, content in language.files.items()}
