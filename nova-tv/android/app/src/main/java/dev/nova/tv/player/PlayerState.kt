package dev.nova.tv.player

/**
 * Chrome visibility as a predicate over state, not a timer that mutates a flag.
 *
 * The rule is lifted from video.js v10 `controls.ts` `computeVisible()`: controls
 * are shown when something holds them, or the media is not playing, or the user
 * is active. A paused film must never hide its own controls, or the viewer is
 * stranded with no way to resume.
 */
enum class HoldReason { LOCK, PAUSED, INTERACTING, MENU, ERROR, ENDED, CASTING, BUFFERING }

data class PlayerUiState(
    val playing: Boolean = false,
    val buffering: Boolean = false,
    val ended: Boolean = false,
    val error: String? = null,
    val menuOpen: Boolean = false,
    val holds: Set<HoldReason> = emptySet(),
    val userActive: Boolean = true,
    val positionMs: Long = 0L,
    val durationMs: Long = 0L,
    val volume: Float = 1f,
    val muted: Boolean = false,
    val playbackRate: Float = 1f
) {
    /** video.js: any hold, or paused, or ended, or errored, or menu open wins. */
    val chromeVisible: Boolean
        get() = when {
            holds.isNotEmpty() -> true
            ended -> true
            error != null -> true
            menuOpen -> true
            !playing -> true
            buffering -> userActive
            else -> userActive
        }

    val progress: Float
        get() = if (durationMs <= 0L) 0f else (positionMs.toFloat() / durationMs).coerceIn(0f, 1f)
}

/** Seek response shapes, matching what the browser player already uses. */
sealed interface SeekResult {
    data class SeekedTo(val targetMs: Long) : SeekResult
    data class Clamped(val targetMs: Long, val bound: String) : SeekResult
    data class Ignored(val reason: String) : SeekResult
}

/**
 * Timings are imported, not invented here.
 *
 * `ImportedTimings.kt` is generated by `python/scripts/import_player_core.py`
 * from the web player that these values were tuned against. Keeping this object
 * as a thin alias means the Android player follows the proven implementation,
 * and re-running the import updates both without a second place to edit.
 */
object PlayerTimings {
    const val IDLE_MS = ImportedTimings.IDLE_MS
    const val IDLE_TOUCH_MS = ImportedTimings.IDLE_TOUCH_MS
    const val TAP_THRESHOLD_MS = ImportedTimings.TAP_THRESHOLD_MS
    const val TOUCH_SETTLE_MS = ImportedTimings.TOUCH_SETTLE_MS
    const val CAPTURE_RELEASE_MS = ImportedTimings.CAPTURE_RELEASE_MS
    const val DOUBLE_TAP_MS = ImportedTimings.DOUBLE_TAP_MS
    const val LONG_PRESS_MS = ImportedTimings.LONG_PRESS_MS
    const val SEEK_SETTLE_MS = ImportedTimings.SEEK_SETTLE_MS
}

object SkipSeconds {
    const val TAP = ImportedSkipSeconds.TAP
    const val KEY = ImportedSkipSeconds.KEY
    const val HOLD = ImportedSkipSeconds.HOLD
}

/**
 * How far short of the end a seek is allowed to land.
 *
 * Landing exactly on `duration` puts ExoPlayer into STATE_ENDED, which the
 * player reads as "the episode finished": it either rolls into the next
 * episode or restarts the current one. That is exactly the "skip forward a few
 * seconds and the whole episode restarts" symptom. Stopping 1.5 s short keeps
 * the seek a seek.
 */
const val SEEK_END_GUARD_MS = 1_500L

fun seekBy(positionMs: Long, deltaMs: Long, durationMs: Long): SeekResult {
    val from = positionMs.coerceAtLeast(0L)
    val target = (from + deltaMs).coerceAtLeast(0L)

    // Duration is C.TIME_UNSET (negative) for the first moments after prepare,
    // and stays unset for some live/HLS sources. A relative seek does not need
    // it: "ten seconds forward from here" is always a valid request. Returning
    // Ignored here is why the ±10 s buttons did nothing on slow sources.
    if (durationMs <= 0L) {
        return if (target == 0L && deltaMs < 0L) SeekResult.Clamped(0L, "start")
        else SeekResult.SeekedTo(target)
    }

    val lastSeekable = (durationMs - SEEK_END_GUARD_MS).coerceAtLeast(0L)
    return when {
        target <= 0L -> SeekResult.Clamped(0L, "start")
        target >= durationMs -> SeekResult.Clamped(lastSeekable, "end")
        else -> SeekResult.SeekedTo(target)
    }
}
