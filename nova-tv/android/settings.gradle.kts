// Build topology adapted from Drjacky/MVVMTemplate (MIT), whose Android CI passes
// on every run. Upstream splits into :app + six :core modules driven by a
// build-logic convention plugin; nova-tv is deliberately one module, so the
// convention plugin is dropped and its effect is expressed directly here.
pluginManagement {
    repositories {
        google {
            content {
                includeGroupByRegex("com\\.android.*")
                includeGroupByRegex("com\\.google.*")
                includeGroupByRegex("androidx.*")
            }
        }
        mavenCentral()
        gradlePluginPortal()
    }
}

dependencyResolutionManagement {
    repositoriesMode.set(RepositoriesMode.FAIL_ON_PROJECT_REPOS)
    repositories {
        google {
            content {
                includeGroupByRegex("com\\.android.*")
                includeGroupByRegex("com\\.google.*")
                includeGroupByRegex("androidx.*")
            }
        }
        mavenCentral()
    }
}

rootProject.name = "NovaTV"

include(":app")
