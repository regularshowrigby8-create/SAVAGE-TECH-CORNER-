# Shared runner for the three Nova guards. Sourced, not executed.
#
# Glue only: every verdict comes from an imported tool (see README.md). This
# file runs each tool, keeps its exit status, and writes one report.
#
# Rules this runner keeps, because breaking them is exactly what the
# anti-false-green guard looks for:
#   * a tool that is not installed is NOT RUN, and NOT RUN fails the guard;
#   * no exit status is discarded (no `|| true`, pipefail on);
#   * the guard's exit status is non-zero if any check failed or did not run.

set -uo pipefail

GUARDS_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
NOVA_DIR="$(cd "$GUARDS_DIR/.." && pwd)"
REPO_ROOT="$(cd "$NOVA_DIR/.." && pwd)"
TOOLS_DIR="${GUARDS_TOOLS_DIR:-$GUARDS_DIR/.tools}"
REPORT_DIR="${GUARDS_REPORT_DIR:-$GUARDS_DIR/reports}"
LOG_DIR="$REPORT_DIR/logs"
export PATH="$TOOLS_DIR/bin:$PATH"

# Versions live here and in install-tools.sh only.
DETEKT_VERSION="1.23.8"
DETEKT_JAR="${DETEKT_JAR:-$TOOLS_DIR/detekt-cli-$DETEKT_VERSION-all.jar}"

# Workflows that belong to Nova. Other workflows in the repository are not
# this guard's to judge.
NOVA_WORKFLOWS=(
  "$REPO_ROOT/.github/workflows/nova-tv-android.yml"
  "$REPO_ROOT/.github/workflows/nova-tv-python.yml"
  "$REPO_ROOT/.github/workflows/nova-guards.yml"
)

GUARD_NAME=""
GUARD_TITLE=""
declare -a ROWS=()
SEP=$'\x1f'
FAILED=0

guard_start() {
  GUARD_NAME="$1"
  GUARD_TITLE="$2"
  mkdir -p "$REPORT_DIR" "$LOG_DIR"
  echo "== $GUARD_TITLE"
}

# check LABEL TOOL -- COMMAND...
# TOOL is the executable or file the check needs ("" for none). A missing tool
# is recorded as NOT RUN and fails the guard.
check() {
  local label="$1" tool="$2"
  shift 2
  [[ "${1:-}" == "--" ]] && shift
  local slug log rc
  slug="$(echo "$GUARD_NAME-$label" | tr 'A-Z' 'a-z' | tr -cs 'a-z0-9' '-' | sed 's/-$//')"
  log="$LOG_DIR/$slug.log"

  if [[ -n "$tool" ]] && ! command -v "$tool" >/dev/null 2>&1 && [[ ! -f "$tool" ]]; then
    echo "  NOT RUN  $label  ($tool is not installed; run guards/install-tools.sh)"
    echo "$tool is not installed. Run nova-tv/guards/install-tools.sh." > "$log"
    ROWS+=("NOT RUN${SEP}$label${SEP}$slug")
    FAILED=1
    gh_annotation error "$label: NOT RUN ($tool missing)"
    return 0
  fi

  echo "  ...      $label"
  "$@" > "$log" 2>&1
  rc=$?
  if [[ $rc -eq 0 ]]; then
    echo "  PASS     $label"
    ROWS+=("PASS${SEP}$label${SEP}$slug")
  else
    echo "  FAIL     $label  (exit $rc)"
    tail -n 40 "$log" | sed 's/^/           /'
    ROWS+=("FAIL${SEP}$label${SEP}$slug")
    FAILED=1
    gh_annotation error "$label failed (exit $rc). See nova-tv/guards/reports/$GUARD_NAME.md"
  fi
  return 0
}

gh_annotation() {
  [[ -n "${GITHUB_ACTIONS:-}" ]] && echo "::$1 title=$GUARD_NAME::$2"
  return 0
}

guard_finish() {
  local out="$REPORT_DIR/$GUARD_NAME.md" row status label slug verdict
  verdict="PASS"
  [[ $FAILED -ne 0 ]] && verdict="FAIL"
  {
    echo "# $GUARD_TITLE: $verdict"
    echo
    echo "Generated by \`nova-tv/guards/$GUARD_NAME.sh\`"
    echo "Commit: \`$(git -C "$REPO_ROOT" rev-parse --short HEAD 2>/dev/null || echo unknown)\`"
    [[ -n "${GITHUB_RUN_ID:-}" ]] && echo "CI run: $GITHUB_RUN_ID"
    echo
    echo "| Result | Check |"
    echo "|---|---|"
    for row in "${ROWS[@]}"; do
      IFS="$SEP" read -r status label slug <<< "$row"
      echo "| $status | ${label//|/\\|} |"
    done
    for row in "${ROWS[@]}"; do
      IFS="$SEP" read -r status label slug <<< "$row"
      [[ "$status" == "PASS" ]] && continue
      echo
      echo "## $status: $label"
      echo
      echo '```'
      tail -n 150 "$LOG_DIR/$slug.log"
      echo '```'
    done
    # A pass is a claim too: keep the end of each passing tool's output as
    # evidence that it ran and what it saw.
    for row in "${ROWS[@]}"; do
      IFS="$SEP" read -r status label slug <<< "$row"
      [[ "$status" == "PASS" ]] || continue
      echo
      echo "<details><summary>PASS: $label (last lines of output)</summary>"
      echo
      echo '```'
      tail -n 30 "$LOG_DIR/$slug.log"
      echo '```'
      echo
      echo "</details>"
    done
  } > "$out"
  [[ -n "${GITHUB_STEP_SUMMARY:-}" ]] && cat "$out" >> "$GITHUB_STEP_SUMMARY"
  echo "== $GUARD_TITLE: $verdict  (report: ${out#"$REPO_ROOT/"})"
  return $FAILED
}

# Run a nova/ JSON tool and fail when its own summary says not ok. The tools
# report "ok": true at the top level whenever they ran, so the top-level flag
# cannot be trusted; the summary is what holds the findings.
nova_tool_summary() {
  local script="$1" command="$2" filter="$3" json
  json="$(mktemp)"
  (cd "$NOVA_DIR/python" && python3 "scripts/$script" "$command" --json) > "$json" || { cat "$json"; rm -f "$json"; return 1; }
  jq -r "$filter" "$json"
  jq -r '.result.summary' "$json"
  jq -e '.result.summary.ok == true' "$json" > /dev/null
  local rc=$?
  rm -f "$json"
  return $rc
}

gradle() {
  (cd "$NOVA_DIR/android" && chmod +x gradlew && ./gradlew --no-daemon --console=plain "$@")
}
