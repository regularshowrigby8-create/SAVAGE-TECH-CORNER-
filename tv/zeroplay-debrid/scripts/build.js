#!/usr/bin/env node
"use strict";
/**
 * Build the browser bundle for lib/**.
 *
 * Why this exists: index.html ships exactly one inline <script>. Everything
 * under lib/ is CommonJS, so the browser can never see it. The old build copied
 * index.html and vendor/ only, which meant every module written for the player
 * and the global resolver was shipped to nobody — it sat in the repo looking
 * finished while the running app changed not at all.
 *
 * No dependencies: a ~40 line module registry is enough for the handful of
 * files involved, and the project rule is no new packages.
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const OUT_DIR = path.join(ROOT, "dist");

/* Entry points, in the order the app may touch them. Each is resolved with the
   same rules as Node so `require("./policy")` from inside global-resolver/ works. */
const ENTRY_FILES = [
  "lib/global-player.js",
  "lib/global-player-bridge.js",
  "lib/global-resolver/policy.js",
  "lib/global-resolver/frontier.js",
  "lib/global-resolver/identity.js",
  "lib/global-resolver/adapters.js",
  "lib/global-resolver/resolver.js",
  "lib/global-resolver/hardening.js"
];

function normalise(p) {
  return p.split(path.sep).join("/");
}

/** Collect every module reachable from the entries. */
function collect(entries) {
  const modules = new Map();
  const queue = entries.map((e) => path.join(ROOT, e));
  while (queue.length) {
    const abs = queue.shift();
    const id = normalise(path.relative(ROOT, abs));
    if (modules.has(id)) continue;
    if (!fs.existsSync(abs)) continue;
    const source = fs.readFileSync(abs, "utf8");
    modules.set(id, source);
    for (const dependency of findRequires(source)) {
      const resolved = resolveRequire(id, dependency);
      if (resolved) queue.push(path.join(ROOT, resolved));
    }
  }
  return modules;
}

function findRequires(source) {
  const found = [];
  const pattern = /require\(\s*["']([^"']+)["']\s*\)/g;
  let match;
  while ((match = pattern.exec(source))) found.push(match[1]);
  return found;
}

/** Only relative requires are bundled; node: builtins are stubbed. */
function resolveRequire(fromId, spec) {
  if (!spec.startsWith(".")) return null;
  const base = path.posix.dirname(fromId);
  let target = path.posix.normalize(path.posix.join(base, spec));
  if (!target.endsWith(".js")) target += ".js";
  return target;
}

function build() {
  const modules = collect(ENTRY_FILES);
  if (!modules.size) {
    console.error("build: no modules found — check ENTRY_FILES");
    process.exit(1);
  }

  const ids = [...modules.keys()];
  const chunks = [];
  chunks.push('/* ZeroPlay browser bundle — generated by scripts/build.js. */');
  chunks.push("(function (global) {");
  chunks.push('  "use strict";');
  chunks.push("  var __modules = {};");
  chunks.push("  var __url = { URL: global.URL, URLSearchParams: global.URLSearchParams };");
  chunks.push("  var __cache = {};");
  chunks.push("  // Node builtins the modules mention: present, but only for code paths");
  chunks.push("  // that also run in Node. In a browser they throw if actually used.");
  /* Some modules import node:url only for URL and URLSearchParams, which the
     browser has natively. Map those through instead of failing the module. */
  chunks.push("  function __builtin(name) {");
  chunks.push('    if (name === "node:url" || name === "url") {');
  chunks.push("      return { URL: global.URL, URLSearchParams: global.URLSearchParams };");
  chunks.push("    }");
  /* Failing loudly at *load* time is what kept the finder dead: a module that
     required node:crypto got a throwing stub, the registry swallowed the error,
     and the app ran on with zero sources and no visible symptom. Degrade to a
     clearly-marked no-op instead, and let the caller notice a missing method. */
  chunks.push('    if (global.console) global.console.warn("bundle: node builtin " + name + " unavailable; using a no-op stub");');
  chunks.push('    return {};');
  chunks.push("  }");

  for (const id of ids) {
    const source = modules.get(id);
    const fn = compile(id, source);
    chunks.push("  __modules[" + JSON.stringify(id) + "] = " + fn + ";");
  }

  chunks.push("  function __require(fromId, spec) {");
  chunks.push('    if (spec.indexOf("node:") === 0 || spec === "node:crypto") return __builtin(spec);');
  chunks.push("    var id = __resolve(fromId || \"\", spec);");
  chunks.push("    if (!id || !__modules[id]) {");
  chunks.push("      // A missing optional dependency is not fatal: callers guard on the");
  chunks.push("      // return value, and a hard throw here would take the whole app down.");
  chunks.push("      return {};");
  chunks.push("    }");
  chunks.push("    if (__cache[id]) return __cache[id].exports;");
  chunks.push("    var module = { exports: {} };");
  chunks.push("    __cache[id] = module;");
  chunks.push("    __modules[id](module, module.exports, function (s) { return __require(id, s); });");
  chunks.push("    return module.exports;");
  chunks.push("  }");
  chunks.push("  function __resolve(fromId, spec) {");
  chunks.push('    if (spec.charAt(0) !== ".") return null;');
  chunks.push('    var base = fromId.split("/"); base.pop();');
  chunks.push('    var parts = spec.split("/");');
  chunks.push("    for (var i = 0; i < parts.length; i++) {");
  chunks.push('      if (parts[i] === "." || parts[i] === "") continue;');
  chunks.push('      if (parts[i] === "..") base.pop(); else base.push(parts[i]);');
  chunks.push("    }");
  chunks.push('    var id = base.join("/");');
  chunks.push('    if (id.slice(-3) !== ".js") id += ".js";');
  chunks.push("    return id;");
  chunks.push("  }");

  chunks.push("  var api = {};");
  for (const entry of ENTRY_FILES) {
    chunks.push(
      "  try { api[" + JSON.stringify(entry) + "] = __require(null, " + JSON.stringify("./" + entry) + "); }" +
      " catch (e) { if (global.console) global.console.warn('bundle: " + entry + " failed', e && e.message); }"
    );
  }
  chunks.push("  global.ZeroPlayLib = api;");
  chunks.push("})(typeof window !== \"undefined\" ? window : this);");
  chunks.push("");

  return chunks.join("\n");
}

/** Wrap a CommonJS file in a function body, leaving the source readable. */
function compile(id, source) {
  return (
    "function (module, exports, require) {\n" +
    "/* ---- " + id + " ---- */\n" +
    source +
    "\n}"
  );
}

function injectScript(html) {
  const tag = '<script src="app.bundle.js"></script>';
  if (html.includes(tag)) return html;
  /* Immediately before the app's own inline script, so ZeroPlayLib exists by
     the time the app touches it. */
  const marker = "<script>";
  const index = html.indexOf(marker);
  if (index < 0) throw new Error("build: no inline <script> found in index.html");
  return html.slice(0, index) + tag + "\n" + html.slice(index);
}

function main() {
  const bundle = build();
  fs.mkdirSync(OUT_DIR, { recursive: true });
  fs.writeFileSync(path.join(OUT_DIR, "app.bundle.js"), bundle, "utf8");

  const html = fs.readFileSync(path.join(ROOT, "index.html"), "utf8");
  fs.writeFileSync(path.join(OUT_DIR, "index.html"), injectScript(html), "utf8");

  fs.mkdirSync(path.join(OUT_DIR, "vendor"), { recursive: true });
  for (const file of ["hls.min.js", "dash.min.js"]) {
    const from = path.join(ROOT, "vendor", file);
    if (fs.existsSync(from)) fs.copyFileSync(from, path.join(OUT_DIR, "vendor", file));
  }

  const size = Buffer.byteLength(bundle, "utf8");
  console.log("ZeroPlay static build complete");
  console.log("  dist/app.bundle.js  " + Math.round(size / 1024) + " KB, " + (bundle.match(/---- /g) || []).length + " modules");
  console.log("  dist/index.html     loads app.bundle.js before the app script");
}

main();
