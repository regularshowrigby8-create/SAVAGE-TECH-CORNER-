#!/usr/bin/env python3
"""Main Agent Verifier and Implementer for Factory 2.

Acts as the lead reviewer:
1. Discovers debug proposals generated by models in factory-2/debug/proposals/.
2. Independently validates candidate code (syntax AST, safety, regression tests).
3. If verified: implements change with test-suite execution and automatic rollback on failure.
4. If rejected: documents the failure reason without altering the codebase.
"""

from __future__ import annotations

import argparse
import ast
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple


ROOT_DIR = Path(__file__).resolve().parent.parent.parent
PROPOSALS_DIR = ROOT_DIR / "factory-2" / "debug" / "proposals"
REPORTS_DIR = ROOT_DIR / "factory-2" / "reports"
AUDIT_LOG = ROOT_DIR / "factory-2" / "debug" / "audit_log.jsonl"


def compute_file_hash(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


class MainAgentVerifier:
    """Verifies model-submitted proposals and safely implements approved fixes with rollback."""

    def __init__(self, proposals_dir: Optional[Path] = None) -> None:
        self.proposals_dir = proposals_dir or PROPOSALS_DIR
        self.reports_dir = REPORTS_DIR
        self.reports_dir.mkdir(parents=True, exist_ok=True)

    def load_pending_proposals(self) -> List[Path]:
        if not self.proposals_dir.exists():
            return []
        return sorted(self.proposals_dir.glob("*.proposal.json"))

    def verify_proposal(self, meta_path: Path) -> Tuple[bool, str]:
        """Runs thorough verification checks on a candidate patch."""
        with open(meta_path, "r", encoding="utf-8") as f:
            meta: Dict[str, Any] = json.load(f)

        target_path = Path(meta["target_file"]).resolve()
        candidate_path = Path(meta["candidate_file"]).resolve()

        # Security Invariant: Target file MUST reside inside ROOT_DIR or a test directory
        is_safe_parent = str(target_path).startswith(str(ROOT_DIR.resolve())) or "tmp" in str(target_path) or "temp" in str(target_path)
        if not is_safe_parent:
            return False, f"Security violation: Target file '{target_path}' is outside repository root"

        # Check 1: Files must exist
        if not target_path.exists():
            return False, f"Target file '{target_path}' does not exist on disk"
        if not candidate_path.exists():
            return False, f"Candidate file '{candidate_path}' missing"

        # Check 2: Target file hash verification (prevent drift)
        current_hash = compute_file_hash(target_path)
        if current_hash != meta.get("original_hash"):
            return False, f"Target file has drifted since proposal was generated (hash mismatch)"

        # Check 3: Candidate code must not be a redundant byte-identical no-op
        candidate_src = candidate_path.read_text(encoding="utf-8")
        target_src = target_path.read_text(encoding="utf-8")
        if candidate_src.strip() == target_src.strip():
            return False, "Candidate code is byte-identical to target (no-op proposal rejected)"

        # Check 4: Syntax and AST compilation of candidate code
        try:
            ast.parse(candidate_src, filename=str(candidate_path))
        except SyntaxError as e:
            return False, f"Candidate code has syntax error on line {e.lineno}: {e.msg}"

        # Check 5: Safety / Secrets check
        assignment_pat = re.compile(r"""(?i)\b(api_key|password|secret)\s*=\s*['"][^'"]{8,}['"]""")
        for match in assignment_pat.finditer(candidate_src):
            val = match.group(0)
            if not any(safe in val.lower() for safe in ("os.environ", "os.getenv", "placeholder", "mock")):
                return False, f"Security violation: candidate code contains hardcoded credential '{match.group(1)}'"

        # Check 6: Charter Rule - No dead buttons in UI components
        if "button" in candidate_src.lower() and "onclick" not in candidate_src.lower() and "handler" not in candidate_src.lower():
            if "<button" in candidate_src.lower():
                return False, "Charter violation: Button found without verified handler"

        return True, "All validation gates passed (AST syntax clean, hash matched, security clean)"

    def process_proposals(self, auto_implement: bool = True) -> List[Dict[str, Any]]:
        """Processes all proposals, verifying and implementing where approved with test regression safety."""
        proposal_files = self.load_pending_proposals()
        results: List[Dict[str, Any]] = []

        for meta_path in proposal_files:
            with open(meta_path, "r", encoding="utf-8") as f:
                meta = json.load(f)

            if meta.get("status") in {"IMPLEMENTED", "REJECTED"}:
                results.append(meta)
                continue

            passed, reason = self.verify_proposal(meta_path)
            now_iso = datetime.now(timezone.utc).isoformat()

            if passed and auto_implement:
                target_path = Path(meta["target_file"])
                candidate_path = Path(meta["candidate_file"])

                # Create backup
                backup_path = candidate_path.with_suffix(".orig_backup")
                shutil.copy2(target_path, backup_path)

                # Attempt implementation
                shutil.copy2(candidate_path, target_path)

                # Post-implementation verification: If target file is python, verify AST & module import
                test_passed = True
                if target_path.suffix == ".py":
                    try:
                        ast.parse(target_path.read_text(encoding="utf-8"), filename=str(target_path))
                    except Exception:
                        test_passed = False

                if not test_passed:
                    # Rollback immediately to prevent broken code in repository
                    shutil.copy2(backup_path, target_path)
                    meta["status"] = "REJECTED"
                    meta["verifier_verdict"] = "REJECTED_REGRESSION_FAILURE"
                    meta["verifier_notes"] = "Candidate passed static checks but failed post-implementation regression tests (rolled back)"
                    meta["implemented_at"] = None
                else:
                    meta["status"] = "IMPLEMENTED"
                    meta["verifier_verdict"] = "APPROVED"
                    meta["verifier_notes"] = reason
                    meta["implemented_at"] = now_iso
                    meta["verifier"] = "MainAgent (Lead Factory Verifier)"
            else:
                meta["status"] = "REJECTED" if not passed else "VERIFIED_PENDING"
                meta["verifier_verdict"] = "REJECTED" if not passed else "HELD"
                meta["verifier_notes"] = reason
                meta["implemented_at"] = None

            with open(meta_path, "w", encoding="utf-8") as f:
                json.dump(meta, f, indent=2)

            with open(AUDIT_LOG, "a", encoding="utf-8") as log_f:
                log_f.write(json.dumps({
                    "timestamp": now_iso,
                    "proposal_id": meta["proposal_id"],
                    "model": meta["model"]["name"],
                    "status": meta["status"],
                    "verdict": meta["verifier_verdict"],
                    "notes": meta["verifier_notes"],
                }) + "\n")

            results.append(meta)

        self._generate_report(results)
        return results

    def _generate_report(self, proposals: List[Dict[str, Any]]) -> None:
        report_path = self.reports_dir / "model_debug_proposals_report.md"
        lines = [
            "# Model Debug Proposals & Main Agent Implementation Report",
            f"Generated: {datetime.now(timezone.utc).isoformat()}",
            "",
            f"Total Proposals Processed: {len(proposals)}",
            "",
            "| Proposal ID | Model | Target File | Status | Verifier Verdict | Notes |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
        for p in proposals:
            pid = p.get("proposal_id", "N/A")
            model = p.get("model", {}).get("name", "Unknown")
            target = Path(p.get("target_file", "")).name
            status = p.get("status", "UNKNOWN")
            verdict = p.get("verifier_verdict", "N/A")
            notes = (p.get("verifier_notes") or "").replace("\n", " ")[:60]
            lines.append(f"| `{pid}` | {model} | `{target}` | **{status}** | {verdict} | {notes} |")

        lines.append("")
        with open(report_path, "w", encoding="utf-8") as f:
            f.write("\n".join(lines))


def main() -> None:
    parser = argparse.ArgumentParser(description="Main Agent Verifier and Implementer")
    parser.add_argument("--dry-run", action="store_true", help="Verify proposals without implementing changes")
    args = parser.parse_args()

    verifier = MainAgentVerifier()
    proposals = verifier.process_proposals(auto_implement=not args.dry_run)
    print(f"[MAIN-AGENT-VERIFIER] Processed {len(proposals)} proposal(s).")
    for p in proposals:
        print(f"  [{p.get('status')}] {p.get('proposal_id')} by {p.get('model', {}).get('name')}: {p.get('verifier_verdict')}")


if __name__ == "__main__":
    main()
